//! PATH shims: capture test and build runs without changing their output (#289).
//!
//! A shim is a two-line `sh` script named after a tool. The shell has already
//! split the command line, so the shim receives the exact argv: there is no
//! reparsing, and it works inside pipes, loops, subshells, and `cd &&`
//! chains. Progressive commands (per the route classifier) are streamed
//! through byte-for-byte while a copy is recorded as an ordinary `run`
//! observation; everything else is `exec`'d directly.

use std::{fs, os::unix::process::CommandExt};

use crate::commands::run::{
    PassthroughCapture, RunSpawn, SHIM_ACTIVE_ENV, capture_passthrough, run_command_with,
};
use crate::*;

pub(crate) const SHIM_SCHEMA: &str = "prog.shims";
const SHIM_HEADER: &str =
    "# prog-shim: generated by `prog shim install`; remove with `prog shim uninstall`.";
const SHIM_MARKER: &str = ".prog-shims.json";
/// Directory under the store holding one empty marker per shim capture whose
/// receipt has not been read yet (`prog receipt --pending`).
pub(crate) const PENDING_RECEIPTS_DIR: &str = "receipts-pending";
const SHIM_CAPTURE_BYTES: usize = 8 * 1024 * 1024;

/// Test, build, and lint entry points. `rustc` and `git` are deliberately
/// absent: Cargo invokes `rustc` once per crate and agents call `git`
/// constantly, so shimming them would add overhead to every compile or query.
pub(crate) const DEFAULT_SHIM_TOOLS: &[&str] = &[
    "cargo",
    "pytest",
    "py.test",
    "go",
    "npm",
    "pnpm",
    "yarn",
    "bun",
    "deno",
    "jest",
    "vitest",
    "playwright",
    "tsc",
    "ruff",
    "biome",
    "uv",
];

pub(crate) fn default_shim_dir() -> PathBuf {
    xdg_dir("XDG_DATA_HOME", ".local/share").join("prog/shims")
}

fn xdg_dir(variable: &str, fallback: &str) -> PathBuf {
    std::env::var_os(variable)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(fallback)))
        .unwrap_or_else(|| PathBuf::from(".prog-shims"))
}

/// A per-project store outside the project tree, so captures never appear as
/// untracked workspace changes (which would make every readiness check stale).
pub(crate) fn project_store_dir(project: &Path) -> PathBuf {
    let canonical = project
        .canonicalize()
        .unwrap_or_else(|_| project.to_path_buf());
    let digest = format!(
        "{:x}",
        Sha256::digest(canonical.to_string_lossy().as_bytes())
    );
    let name = canonical
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("project")
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_' | '.') {
                ch
            } else {
                '_'
            }
        })
        .collect::<String>();
    xdg_dir("XDG_STATE_HOME", ".local/state")
        .join("prog/projects")
        .join(format!("{name}-{}", &digest[..12]))
}

pub(crate) fn shim_install(args: &ShimInstallArgs) -> Result<Value> {
    let dir = args.dir.clone().unwrap_or_else(default_shim_dir);
    fs::create_dir_all(&dir)?;
    let prog = std::env::current_exe()?;
    let tools = if args.tools.is_empty() {
        DEFAULT_SHIM_TOOLS
            .iter()
            .map(|tool| (*tool).to_string())
            .collect()
    } else {
        args.tools.clone()
    };
    let mut installed = Vec::new();
    for tool in &tools {
        validate_tool_name(tool)?;
        let path = dir.join(tool);
        let script = shim_script(&prog, &dir, tool);
        let action = match fs::read_to_string(&path) {
            Ok(existing) if existing == script => "unchanged",
            Ok(existing) if existing.contains(SHIM_HEADER) => "updated",
            Ok(_) => "exists",
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => "created",
            Err(_) => "exists",
        };
        if matches!(action, "created" | "updated") {
            fs::write(&path, &script)?;
            fs::set_permissions(&path, std::os::unix::fs::PermissionsExt::from_mode(0o755))?;
        }
        installed.push(json!({"tool": tool, "path": path, "action": action}));
    }
    fs::write(
        dir.join(SHIM_MARKER),
        serde_json::to_vec_pretty(&json!({
            "schema": SHIM_SCHEMA,
            "prog": prog,
            "tools": tools,
        }))?,
    )?;
    Ok(json!({
        "schema": SHIM_SCHEMA,
        "dir": dir,
        "prog": prog,
        "shims": installed,
        "activate": format!("prepend {} to PATH (see `prog shim env`)", dir.display()),
    }))
}

pub(crate) fn shim_uninstall(args: &ShimDirArgs) -> Result<Value> {
    let dir = args.dir.clone().unwrap_or_else(default_shim_dir);
    let mut removed = Vec::new();
    if let Ok(entries) = fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            let ours = fs::read_to_string(&path).is_ok_and(|text| text.contains(SHIM_HEADER));
            if ours {
                fs::remove_file(&path)?;
                removed.push(path);
            }
        }
    }
    let marker = dir.join(SHIM_MARKER);
    if marker.exists() {
        fs::remove_file(&marker)?;
    }
    // Only an emptied directory is removed; anything else stays.
    let _ = fs::remove_dir(&dir);
    Ok(json!({"schema": SHIM_SCHEMA, "dir": dir, "removed": removed}))
}

/// Shell lines that activate the shims (idempotently) and, for a project, a
/// dedicated store outside the project tree.
pub(crate) fn shim_env(args: &ShimEnvArgs) -> Value {
    let dir = args.dir.clone().unwrap_or_else(default_shim_dir);
    // The quoted directory is matched literally in the `case` pattern too, so
    // quotes or `$` in its name can neither break nor expand the line.
    let quoted = source_shell_quote(&dir.to_string_lossy());
    let mut exports =
        format!("case \":$PATH:\" in *:{quoted}:*) ;; *) export PATH={quoted}\":$PATH\" ;; esac\n");
    let store = args.project.as_deref().map(project_store_dir);
    if let Some(store) = &store {
        exports.push_str(&format!(
            "export PROG_DIR={}\n",
            source_shell_quote(&store.to_string_lossy())
        ));
    }
    json!({
        "schema": "prog.shim_env",
        "shim_dir": dir,
        "prog_dir": store,
        "exports": exports,
    })
}

fn shim_script(prog: &Path, dir: &Path, tool: &str) -> String {
    format!(
        "#!/bin/sh\n{SHIM_HEADER}\nexec {} shim exec --shim-dir {} -- {} \"$@\"\n",
        source_shell_quote(&prog.to_string_lossy()),
        source_shell_quote(&dir.to_string_lossy()),
        source_shell_quote(tool),
    )
}

fn source_shell_quote(value: &str) -> String {
    crate::commands::source::shell_quote(value)
}

fn validate_tool_name(tool: &str) -> Result<()> {
    let valid = !tool.is_empty()
        && tool
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '.' | '_' | '-'))
        && tool != "."
        && tool != ".."
        && tool != "prog";
    if valid {
        Ok(())
    } else {
        Err(CoreError::BadArgs {
            operation: "shim install".to_string(),
            reason: format!("'{tool}' is not a valid tool name"),
        })
    }
}

/// The tool this shim stands in for: the first executable on `PATH` outside
/// the shim directory that is not itself a prog shim. Skipping every shim,
/// not just this directory's, keeps two shim directories on `PATH` from
/// `exec`ing each other forever.
fn resolve_real_tool(tool: &str, shim_dir: &Path) -> Option<PathBuf> {
    let shim_dir = shim_dir
        .canonicalize()
        .unwrap_or_else(|_| shim_dir.to_path_buf());
    std::env::var_os("PATH").and_then(|path| {
        std::env::split_paths(&path)
            .filter(|entry| !entry.as_os_str().is_empty())
            .filter(|entry| entry.canonicalize().map_or(true, |entry| entry != shim_dir))
            .map(|entry| entry.join(tool))
            .find(|candidate| {
                fs::metadata(candidate).is_ok_and(|metadata| {
                    metadata.is_file()
                        && std::os::unix::fs::PermissionsExt::mode(&metadata.permissions()) & 0o111
                            != 0
                }) && !is_prog_shim(candidate)
            })
    })
}

/// Whether `path` is a script written by `prog shim install`. The header is
/// on its second line, so only the first bytes are read.
fn is_prog_shim(path: &Path) -> bool {
    use std::io::Read;

    let mut head = Vec::with_capacity(256);
    fs::File::open(path)
        .and_then(|file| file.take(256).read_to_end(&mut head))
        .is_ok_and(|_| {
            head.windows(SHIM_HEADER.len())
                .any(|window| window == SHIM_HEADER.as_bytes())
        })
}

/// Run one tool for a shim script. Never prints anything of its own: the
/// caller sees exactly the tool's bytes and exit status.
pub(crate) async fn shim_exec(
    dir: &Path,
    args: &ShimExecArgs,
    ctx: &mut InvocationContext,
) -> ExitCode {
    let tool = &args.command[0];
    let Some(real) = resolve_real_tool(tool, &args.shim_dir) else {
        eprintln!("{tool}: command not found");
        return ExitCode::from(127);
    };
    let nested = std::env::var(SHIM_ACTIVE_ENV).is_ok_and(|value| value == "1");
    let progressive = prog_core::classify_route(&args.command, &prog_core::RoutePolicy::default())
        .guidance
        == prog_core::RouteGuidance::Progressive;
    if nested || !progressive {
        let error = std::process::Command::new(&real)
            .arg0(tool)
            .args(&args.command[1..])
            .exec();
        eprintln!("{tool}: {error}");
        return ExitCode::from(126);
    }

    let started_at = Utc::now();
    let started_instant = Instant::now();
    let real_for_capture = real.clone();
    let argv = args.command.clone();
    let captured = tokio::task::spawn_blocking(move || {
        capture_passthrough(
            &real_for_capture,
            &argv,
            SHIM_CAPTURE_BYTES,
            SHIM_CAPTURE_BYTES,
        )
    })
    .await;
    let Ok(result) = captured else {
        return ExitCode::from(126);
    };
    let outcome = shim_outcome(&result.status);
    if let RunProcessStatus::SpawnError(error) = &result.status {
        eprintln!("{tool}: {error}");
        return ExitCode::from(126);
    }

    // Recording is best effort: a store problem must never change what the
    // caller sees, so every failure here is silent.
    if let Ok(store) = Store::open_silently(dir) {
        let run_args = RunArgs {
            timeout_ms: 0,
            max_stdout_bytes: SHIM_CAPTURE_BYTES,
            max_stderr_bytes: SHIM_CAPTURE_BYTES,
            ttl_seconds: 86_400,
            preserve_exit_code: true,
            out: None,
            lens: None,
            comparison_family: None,
            selection_scopes: Vec::new(),
            selection_exhaustive: false,
            command: args.command.clone(),
        };
        let recorded = run_command_with(
            &store,
            None,
            &run_args,
            ctx,
            RunSpawn::Precaptured(PassthroughCapture {
                result,
                started_at,
                started_instant,
            }),
        )
        .await;
        if let Ok(recorded) = recorded
            && let Some(id) = recorded
                .envelope
                .observation
                .as_ref()
                .and_then(|observation| observation.observation_id.as_ref())
        {
            let pending = dir.join(PENDING_RECEIPTS_DIR);
            if fs::create_dir_all(&pending).is_ok() {
                let _ = fs::write(pending.join(id), b"");
            }
        }
    }
    finish_like_child(outcome)
}

enum ShimOutcome {
    Code(u8),
    Signal(i32),
}

fn shim_outcome(status: &RunProcessStatus) -> ShimOutcome {
    match status {
        RunProcessStatus::Exited {
            signal: Some(signal),
            ..
        } => ShimOutcome::Signal(*signal),
        RunProcessStatus::Exited { code, .. } => {
            ShimOutcome::Code(code.map_or(1, |code| u8::try_from(code & 0xff).unwrap_or(1)))
        }
        RunProcessStatus::TimedOut => ShimOutcome::Code(124),
        RunProcessStatus::Cancelled { signal } => ShimOutcome::Signal(*signal),
        RunProcessStatus::SpawnError(_) => ShimOutcome::Code(126),
    }
}

/// Exit exactly as the tool did: same code, or die by the same signal.
fn finish_like_child(outcome: ShimOutcome) -> ExitCode {
    match outcome {
        ShimOutcome::Code(code) => ExitCode::from(code),
        ShimOutcome::Signal(signal) => {
            // SAFETY: restoring the default disposition and re-raising the
            // child's terminating signal on this process.
            unsafe {
                libc::signal(signal, libc::SIG_DFL);
                libc::raise(signal);
            }
            ExitCode::from(128u8.saturating_add(u8::try_from(signal).unwrap_or(0)))
        }
    }
}
